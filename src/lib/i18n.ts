const DICTS: Record<Lang, Record<Key, string>> = { fr, en };

export function t(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
	const text = DICTS[lang][key] ?? fr[key];
	return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

/** Translator for one language, for components: `const tr = translator(lang)`. */
export function translator(lang: Lang) {
	return (key: Key, params?: Record<string, string | number>) => t(lang, key, params);
}

/** A label for a key that may not be in the dictionaries (a new category from the API): the raw value. */
export function tOr(lang: Lang, key: string, fallback: string): string {
	return key in fr ? t(lang, key as Key) : fallback;
}

/** The country's name in the reader's language (from the browser's or Node's own data). */
export function countryName(lang: Lang, cc: string): string {
	try {
		return new Intl.DisplayNames([lang], { type: 'region' }).of(cc.toUpperCase()) ?? cc.toUpperCase();
	} catch {
		return cc.toUpperCase();
	}
}
