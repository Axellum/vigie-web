// The site's own texts, in French and English. Official warning texts are never here: they are shown as
// the issuer wrote them.
export type Lang = 'fr' | 'en';
export const LANGS: Lang[] = ['fr', 'en'];

export function asLang(value: string | null | undefined): Lang | null {
	const v = (value ?? '').toLowerCase().slice(0, 2);
	return v === 'fr' || v === 'en' ? v : null;
}

/** The first supported language of an Accept-Language header, French by default. */
export function langFromHeader(header: string | null): Lang {
	for (const part of (header ?? '').split(',')) {
		const lang = asLang(part.trim());
		if (lang) return lang;
	}
	return 'fr';
}

