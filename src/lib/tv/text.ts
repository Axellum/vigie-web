export type TvKey = keyof (typeof TEXT)['fr'];
/** The table, so that a test can check that both languages have every key. */
export const TV_TEXT = TEXT;

export function tvText(lang: Lang, key: TvKey, vars: Record<string, string | number> = {}): string {
	let text: string = TEXT[lang][key] ?? TEXT.fr[key];
	for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
	return text;
}

export const verdictWord = (lang: Lang, v: 'good' | 'possible' | 'poor' | null): string =>
	tvText(lang, `verdict.${v ?? 'unknown'}` as TvKey);
export const activityLabel = (lang: Lang, id: string): string => tvText(lang, `activity.${id}` as TvKey);
export const activityShort = (lang: Lang, id: string): string => tvText(lang, `short.${id}` as TvKey);
